export type Lang = "en" | "zh-CN";
export type T = (key: Key, vars?: Record<string, string | number>) => string;

const catalogues: Record<Lang, Record<Key, string>> = { en, "zh-CN": zh };

/** resolveLang picks the interface language: the setting, else the system's. */
export function resolveLang(setting?: string): Lang {
  if (setting === "en" || setting === "zh-CN") return setting;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translator(lang: Lang): T {
  const table = catalogues[lang];
  return (key, vars) => {
    let s = table[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export const I18n = createContext<{ lang: Lang; t: T; setLang: (setting: string) => void }>({
  lang: "en",
  t: translator("en"),
  setLang: () => {},
});

export const useI18n = () => useContext(I18n);
